// criar um sistema que valide se o nome do mês digitado é valido!

// ============================================================================================= Switch Case =====================================================================================
var month = "Janeiro"

switch (month) {
    case "Janeiro":
    case "Fevereiro":
    case "Março":
    case "Abril":
    case "Maio":
    case "Junho":
    case "Julho":
    case "Agosto":
    case "Setembro":
    case "Outubro":
    case "Novembro":
    case "Dezembro":
        console.log("Mês Válido!!")
        break
    default:
        console.log("Mês Inválido!!!")
}


