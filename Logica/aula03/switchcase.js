// Verificar se a letra digitada é vogal ou constante
// A E I O U

var letraDigitada = "E"

switch (letraDigitada) {
    case "A": // Casos
        console.log("É uma vogal!!!")
        break // Parar

    case "E": // Casos
        console.log("É uma vogal!!!")
        break // Parar

    case "I": // Casos
        console.log("É uma vogal!!!")
        break // Parar

    case "O": // Casos
        console.log("É uma vogal!!!")
        break // Parar

    case "U": // Casos
        console.log("É uma vogal!!!")
        break // Parar

    default: // Padrão
        console.log("É uma consoante!!!")
}



