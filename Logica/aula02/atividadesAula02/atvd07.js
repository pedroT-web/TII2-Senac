// Faça um programa que leia um número e verifique se ele está entre 1 e 100.
var number = 101
if (number > 0) {
    if (number <= 100) {
        console.log("O número está entre 1 e 100.")
    } else {
        console.log("O número não está entre 1 e 100")
    }
} else {
    console.log("O número não está entre 1 e 100")
}