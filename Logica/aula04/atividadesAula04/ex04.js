// Implemente uma contagem regressiva de 10 até 0 utilizando um laço de repetição (USANDO O WHILE E FOR).
var i = 10

console.log("\nWhile\n")
console.log("Contagem Regressiva!!!")
while (i >= 0) {
    console.log(i)

    i--
}

console.log("\nFOR\n")
console.log("Contagem Regressiva!!!")
for(i = 10; i >= 0; i--){
    console.log(i)
}